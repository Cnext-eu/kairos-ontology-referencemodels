#!/usr/bin/env python3
"""Generate skos:exactMatch links from IATA ONE Record codes to UNECE codes (gh#120).

The vendored IATA code lists profile two UNECE recommendations without a machine-readable
link to them:

* ``code-lists:ModeCode`` (Rec 19) — the code exists only in prose, as the trailing
  ``(N)`` of each individual's ``rdfs:comment`` ("... Air Transport (4)").
* ``code-lists:MeasurementUnitCode`` (Rec 20) — the code is the individual's local name
  (``MeasurementUnitCode#KGM``); IATA extends the list with cXML units that Rec 20 lacks.

This script reads both vendored files and writes ``UNCEFACT-IATA-alignment.ttl`` next to
the UN/CEFACT extract. Every link is derived mechanically from the two upstreams; an
IATA code with no UNECE counterpart is listed in the file header instead of guessed.

Regenerate after refreshing either vendored source:
    python scripts/generate_uncefact_iata_alignment.py
"""
import re
import sys
from pathlib import Path

from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import OWL, RDF, RDFS, SKOS

REPO_ROOT = Path(__file__).resolve().parent.parent
AUTHORITATIVE = (
    REPO_ROOT / "kairos_ontology_referencemodels" / "ontology-reference-models" / "authoritative-ontologies"
)
IATA_CL_TTL = AUTHORITATIVE / "IATA" / "current" / "IATA-1R-CL-Ontology.ttl"
UNCEFACT_DIR = AUTHORITATIVE / "UNCEFACT" / "current"
UNCEFACT_TTL = UNCEFACT_DIR / "UNCEFACT-CodeLists.ttl"
OUTPUT_TTL = UNCEFACT_DIR / "UNCEFACT-IATA-alignment.ttl"

ONTOLOGY_IRI = URIRef("https://www.kairosflow.ai/ont/uncefact/iata-alignment")
IATA_CL = Namespace("https://onerecord.iata.org/ns/code-lists/")
UNECE = Namespace("https://vocabulary.uncefact.org/")

TRAILING_CODE_RE = re.compile(r"\((\d)\)\s*$")


def unece_codes(graph: Graph, code_list: str) -> dict[str, URIRef]:
    return {str(graph.value(member, RDF.value)): member for member in graph.subjects(RDF.type, UNECE[code_list])}


def align_modes(iata: Graph, rec19: dict[str, URIRef]):
    links, unmatched = [], []
    for member in sorted(iata.subjects(RDF.type, IATA_CL.ModeCode)):
        comments = [str(c) for c in iata.objects(member, RDFS.comment)]
        codes = {m.group(1) for c in comments if (m := TRAILING_CODE_RE.search(c))}
        if len(codes) == 1 and (code := codes.pop()) in rec19:
            links.append((member, rec19[code]))
        else:
            unmatched.append(member)
    return links, unmatched


def align_units(iata: Graph, rec20: dict[str, URIRef]):
    links, unmatched = [], []
    for member in sorted(iata.subjects(RDF.type, IATA_CL.MeasurementUnitCode)):
        code = str(member).rpartition("#")[2]
        if code in rec20:
            links.append((member, rec20[code]))
        else:
            unmatched.append(member)
    return links, unmatched


def main() -> int:
    iata = Graph().parse(IATA_CL_TTL)
    unece = Graph().parse(UNCEFACT_TTL)
    mode_links, mode_unmatched = align_modes(iata, unece_codes(unece, "TransportModeCodeList"))
    unit_links, unit_unmatched = align_units(iata, unece_codes(unece, "UnitMeasureCode"))
    if not mode_links or not unit_links:
        print("ERROR: an alignment came back empty; did an upstream change shape?", file=sys.stderr)
        return 1

    unmatched = mode_unmatched + unit_unmatched
    out = Graph()
    out.bind("skos", SKOS)
    out.bind("iata-cl", IATA_CL)
    out.bind("unece", UNECE)
    out.add((ONTOLOGY_IRI, RDF.type, OWL.Ontology))
    out.add((ONTOLOGY_IRI, RDFS.label, Literal("IATA ONE Record to UN/CEFACT code alignment")))
    out.add((
        ONTOLOGY_IRI,
        RDFS.comment,
        Literal(
            "skos:exactMatch from IATA ONE Record code-list individuals to the UNECE codes they "
            f"profile: {len(mode_links)} ModeCode -> Rec 19 (matched on the '(N)' code in "
            f"rdfs:comment), {len(unit_links)} MeasurementUnitCode -> Rec 20 (matched on the "
            "local name). IATA codes with no UNECE counterpart, left unlinked: "
            + (", ".join(str(m).rpartition("/")[2] for m in unmatched) or "none")
            + ". Generated by scripts/generate_uncefact_iata_alignment.py; do not hand-edit."
        ),
    ))
    for iata_code, unece_code in mode_links + unit_links:
        out.add((iata_code, SKOS.exactMatch, unece_code))
    out.serialize(OUTPUT_TTL, format="turtle", encoding="utf-8")

    print(f"  ModeCode -> Rec 19: {len(mode_links)} linked, {len(mode_unmatched)} unmatched")
    print(f"  MeasurementUnitCode -> Rec 20: {len(unit_links)} linked, {len(unit_unmatched)} unmatched")
    if unmatched:
        print("  unmatched: " + ", ".join(str(m).rpartition("/")[2] for m in unmatched))
    print(f"Wrote {OUTPUT_TTL.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
